function choice(
  grade: Grade,
  section: Exclude<Section, 'writing'>,
  sequence: 1 | 2,
  title: LocalizedText,
  prompt: LocalizedText,
  correct: LocalizedText,
  distractors: readonly [LocalizedText, LocalizedText, LocalizedText],
  answerIndex: number,
  explanation: LocalizedText,
  audioTextKo?: string,
): TopikOwnerBatch6Draft {
  const choices = [...distractors];
  choices.splice(answerIndex, 0, correct);
  return {
    id: `topik-owner-batch6-grade${grade}-${section}-${sequence}`,
    grade,
    section,
    sequence,
    title,
    prompt,
    choices,
    answer_index: answerIndex,
    explanation,
    audio_text_ko: section === 'listening' ? audioTextKo ?? null : null,
    speech_provider: section === 'listening' ? 'google-browser' : 'unavailable',
    authorship: 'self-authored',
    source_evidence_hash: NEXT_CONTENT_EXPANSION_SOURCE_EVIDENCE.intakeArtifactSha256,
    reviews: pendingReviews(),
    release_state: 'draft',
    is_published: 0,
  };
}

