function stableRef(item: TopikOwnerBatch6Draft): string {
  return `topik:owner:batch6:grade${item.grade}:${item.section}:${item.sequence}`;
}

function unitId(item: TopikOwnerBatch6Draft): string {
  return `${item.id}-unit`;
}

function answerJson(item: TopikOwnerBatch6Draft): string {
  if (!item.choices) {
    if (!item.rubric) throw new Error(`Constructed-response item is missing a multilingual rubric: ${item.id}`);
    return JSON.stringify({
      sample_answer_ko: item.explanation.ko.replace(/^예: /u, ''),
      sample_answer_ja: item.explanation.ja.replace(/^例：/u, ''),
      sample_answer_en: item.explanation.en.replace(/^Example: /u, ''),
      rubric_ko: item.rubric.ko,
      rubric_ja: item.rubric.ja,
      rubric_en: item.rubric.en,
    });
  }
  return JSON.stringify({
    choices: item.choices.map((candidate) => candidate.ko),
    choices_ko: item.choices.map((candidate) => candidate.ko),
    choices_ja: item.choices.map((candidate) => candidate.ja),
    choices_en: item.choices.map((candidate) => candidate.en),
    answer_index: item.answer_index,
  });
}

